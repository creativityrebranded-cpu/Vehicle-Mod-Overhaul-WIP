bool Copy(void* out, std::uintptr_t address, std::size_t size) {
    __try { std::memcpy(out, reinterpret_cast<const void*>(address), size); return true; }
    __except (EXCEPTION_EXECUTE_HANDLER) { return false; }
}
bool IsNonActorReference(std::uint32_t id) {
    const auto base = verifiedBase.load();
    if (!base) return false;
    __try {
        const auto ref = reinterpret_cast<std::uintptr_t (*)(std::uint32_t)>(base+0x5de3b0)(id);
        if (!ref || *reinterpret_cast<const std::uint8_t*>(ref+0x2e) != 0x4a) return false;
        const auto table = *reinterpret_cast<const std::uintptr_t*>(ref);
        return reinterpret_cast<std::uintptr_t (*)(std::uintptr_t)>(
            *reinterpret_cast<const std::uintptr_t*>(table+0x230))(ref) == ref;
    } __except (EXCEPTION_EXECUTE_HANDLER) { return false; }
}
