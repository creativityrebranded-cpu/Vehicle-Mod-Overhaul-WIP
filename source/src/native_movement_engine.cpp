ControllerApi ResolveControllerApi(std::uintptr_t base) {
    if (!base) return {};
    for (const auto& expected : fingerprints) {
        std::uint8_t found[24];
        if (!Copy(found,base+expected.rva,sizeof found) ||
            std::memcmp(found,expected.bytes,sizeof found) != 0) return {};
    }
    for (const auto& expected : tableSlots) {
        std::uintptr_t found = 0;
        if (!Copy(&found,base+expected.rva,sizeof found) || found != base+expected.function) return {};
    }
    auto previous = std::uintptr_t{0};
    if (!verifiedBase.compare_exchange_strong(previous,base) && previous != base) return {};
    ControllerApi api;
    api.isNonActorReference = &IsNonActorReference;
    api.construct = reinterpret_cast<decltype(api.construct)>(base+0x689180);
    api.destroy = reinterpret_cast<decltype(api.destroy)>(base+0x689600);
    api.activate = reinterpret_cast<decltype(api.activate)>(base+0x2739530);
    api.selectNormal = reinterpret_cast<decltype(api.selectNormal)>(base+0x2738ef0);
    api.lookup = reinterpret_cast<decltype(api.lookup)>(base+0x688b60);
    api.update = reinterpret_cast<decltype(api.update)>(base+0x27342e0);
    api.setGoalKey = reinterpret_cast<const void*>(base+0x5f9d100);
    api.storedOutputKey = reinterpret_cast<const void*>(base+0x5f9d860);
    return api;
}
